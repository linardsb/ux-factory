// renderPack(pkg) → { "flow.md": text, …, "imports/<id>.md": text } — PURE. `pkg` is readBuildPackage's shape.
export function renderPack(pkg) {
  const doc = foldLedger(pkg.ops).doc;
  const out = {
    "flow.md": renderFlow(pkg.slug, doc, pkg.transcript && pkg.transcript.filter((l) => l?.type === "op")),
    "drops.md": renderDrops(pkg.slug, pkg.imports),
    "refusals.md": renderRefusals(pkg.slug, pkg),
    "lineage.json": renderLineage(doc, pkg),
  };
  for (const i of pkg.imports) if (i.md !== null) out[`imports/${i.id}.md`] = i.md;
  return out;
}

// ---- the thin shell ----------------------------------------------------------------------------------

const readJsonl = (file) => readFileSync(file, "utf8").split("\n").flatMap((text, i) => {
  if (!text.trim()) return [];
  try { return [JSON.parse(text)]; }
  catch (e) { throw new Error(`${file} line ${i + 1} is not JSON — ${e.message}`); }
});
const maybe = (file) => (existsSync(file) ? readJsonl(file) : null);

// readBuildPackage(pkgRoot) → { slug, ops, transcript, answers, buildTranscript, imports } — or null when the
// package has no build half.
export function readBuildPackage(pkgRoot) {
  const pkg = loadBuild(join(pkgRoot, "build"));
  if (!pkg) return null;
  const dir = join(pkgRoot, "build", "imports");
  const ids = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort() : [];
  return {
    slug: pkgRoot.split(/[\\/]/).filter(Boolean).pop(),
    ops: pkg.ops,
    transcript: maybe(join(pkgRoot, "transcript.jsonl")),
    answers: maybe(join(pkgRoot, "answers.jsonl")),
    buildTranscript: maybe(join(pkgRoot, "build", "transcript.jsonl")) ?? [],
    imports: ids.map((id) => ({
      id,
      record: (() => {
        try { return JSON.parse(readFileSync(join(dir, `${id}.json`), "utf8")); }
        catch (e) { throw new Error(`${join(dir, `${id}.json`)}: ${e.message}`); }
      })(),
      md: existsSync(join(dir, `${id}.md`)) ? readFileSync(join(dir, `${id}.md`), "utf8") : null,
      transcript: maybe(join(dir, `${id}.transcript.jsonl`)) ?? [],
    })),
  };
}

const walk = (dir) => (existsSync(dir) ? readdirSync(dir).sort().flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
}) : []);

// writeBuildHandoff(pkgRoot) → { dir, files } — the whole pack, rewritten. The imports/ subdir is rebuilt from
// scratch (#64's rule: a removed record leaves no orphaned md). A package with no build half writes nothing.
export function writeBuildHandoff(pkgRoot) {
  const pkg = readBuildPackage(pkgRoot);
  const dir = join(pkgRoot, "build", PACK_DIR);
  if (!pkg) return { dir, files: [] };
  // Render BEFORE the rm: a render that throws leaves the old pack whole, never half old and half empty (PR #491 F3).
  const rendered = renderPack(pkg);
  rmSync(join(dir, "imports"), { recursive: true, force: true });
  const files = [];
  for (const [rel, text] of Object.entries(rendered)) {
    const p = join(dir, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
    files.push(p);
  }
  return { dir, files };
}

// committedPackages() → absolute package roots: every discovery/<slug> and tooling/fixtures/builds/<slug> with a build/.
export const committedPackages = () => PACKAGE_ROOTS.flatMap((dir) =>
  listBuilds([{ provenance: "fictional", dir }]).map((b) => join(dir, b.slug)));

// genBuildHandoff({ check }) → { packages, files, drifted } — check mode compares every rendered file to disk (a
// missing file is drift) and reports every file on disk the render did not produce (an orphan is drift too).
export function genBuildHandoff({ check = false } = {}) {
  const drifted = [];
  let files = 0;
  const roots = committedPackages();
  for (const p of roots) {
    const rendered = renderPack(readBuildPackage(p));
    files += Object.keys(rendered).length;
    if (!check) { writeBuildHandoff(p); continue; }
    const dir = join(p, "build", PACK_DIR);
    for (const [rel, text] of Object.entries(rendered)) {
      let prior;
      try { prior = readFileSync(join(dir, rel), "utf8"); } catch { prior = null; }
      if (prior !== text) drifted.push(relative(ROOT, join(dir, rel)));
    }
    for (const f of walk(dir)) if (!Object.hasOwn(rendered, relative(dir, f).split("\\").join("/"))) drifted.push(`${relative(ROOT, f)} (orphan)`);
  }
  return { packages: roots.length, files, drifted };
}

// pathToFileURL, not `file://${argv[1]}`: this repo's path contains a space.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const at = process.argv.indexOf("--root");
    if (at !== -1) {
      const r = writeBuildHandoff(resolve(process.argv[at + 1] ?? ""));
      console.log(`build handoff  ✓  ${r.files.length} files (${r.dir})`);
    } else {
      const check = process.argv.includes("--check");
      const r = genBuildHandoff({ check });
      if (check && r.drifted.length) {
        console.error(`build handoff ✗  drift: ${r.drifted.join(", ")} — regenerate with: node agent-layer/gen-build-handoff.mjs`);
        process.exit(1);
      }
      console.log(`build handoff  ✓  ${r.packages} packages, ${r.files} files${check ? " — no drift" : ""}`);
    }
  } catch (e) {
    console.error(`build handoff ✗  ${e.message}`);
    process.exit(1);
  }
}
