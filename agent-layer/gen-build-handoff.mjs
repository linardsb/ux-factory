// gen-build-handoff.mjs — a build package → its handoff pack (epic #295 ticket #314;
// docs/epics/canvas-design-import.architecture.md § Data model, "The handoff pack, extended").
// Emits <pkg>/build/handoff/: flow.md (the composition-over-admission count (#315), the state diagram as
// Mermaid stateDiagram-v2 per lane, G5's "tapping Continue goes to …" sentences, missing states per lane), drops.md (every import record's drop
// list in the three classes), refusals.md (the ledger's refused lines, the transcript-only refusals and
// the imports' denied lines), lineage.json (frame → decision → answer → evidence, by id) and
// imports/<id>.md (each record's own projection, verbatim).
//
// BESIDE THE PACKAGE, NEVER UNDER handoff/verdant/. A real package lives in the jobs folder and is never
// committed; its pack travels with it. handoff/verdant/ is the component pack, and gen-pack-index.mjs
// throws on a file there it has no route for.
//
// TWO HALVES: a PURE core (renderPack — no filesystem, no clock; same package in, same bytes out) and a
// THIN shell (readBuildPackage, writeBuildHandoff, genBuildHandoff, the CLI). Every lane read is
// system/canvas-ops.mjs's, so the canvas page, build-checks and this file answer from one code path (G33).
// The fold is canvas-store's foldLedger, so undo and refused lines mean what they mean on the page.
//
// FLAGGED, NEVER DROPPED: an unresolvable decision, answer or evidence ref keeps its row and carries a flag.
// An empty drops.md says "No imports" rather than being left out.
//
// CANNOT REACH: whether Mermaid parses flow.md (a human paste into mermaid.live), whether a drop's reason is
// true (group 42's), whether the page's Write button writes (canvas-journey pass L), whether a decision is a
// good one (a human read), and whether a jobs-folder package's pack is current (the drift leg sees committed
// packages only; the portal regenerates after every write route).
//
// Standalone:  node agent-layer/gen-build-handoff.mjs [--check]
//              node agent-layer/gen-build-handoff.mjs --root <pkgRoot>
// Paths resolve from this module (NOT cwd).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { foldLedger, listBuilds, loadBuild, notPickedOf } from "../portal/lib/canvas-store.mjs";
import { STATE_KEYS, edgePhrase, flowEdges, frameLabel, frameTree, groupInstances, laneDoc, laneKeys, missingStates, staleFrames, stateDiagram } from "../system/canvas-ops.mjs";
import { DROP_CLASSES } from "../import/ir.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const PACK_DIR = "handoff";
export const PACK_FILES = Object.freeze(["flow.md", "drops.md", "refusals.md", "lineage.json"]);
export const PACKAGE_ROOTS = Object.freeze([join(ROOT, "discovery"), join(ROOT, "tooling/fixtures/builds")]);

const one = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const provenance = (what) => `Generated by \`agent-layer/gen-build-handoff.mjs\` from ${what} (#314). Regenerated, never hand-edited: a hand edit is lost.`;

// ---- flow.md -----------------------------------------------------------------------------------------

function differences(doc, key) {
  const v = (doc.variants ?? []).find((x) => x && x.key === key);
  const out = [];
  for (const [fid, ov] of Object.entries(v?.overrides ?? {})) {
    if (ov?.omit === true) { out.push(`- ${one(fid)} · left out of this lane`); continue; }
    for (const [part, props] of Object.entries(ov?.set ?? {})) {
      for (const [prop, value] of Object.entries(props ?? {})) out.push(`- ${one(fid)} · set ${one(part)}.${one(prop)} → ${JSON.stringify(value)}`);
    }
    for (const part of Array.isArray(ov?.hide) ? ov.hide : []) out.push(`- ${one(fid)} · hide ${one(part)}`);
    if (ov?.add !== undefined) out.push(`- ${one(fid)} · add (not rendered; flagged)`);
  }
  return out.length ? out : ["- none"];
}

// compositionCount(doc) → { composed, placed, admitted: { total, fromImport, fromGroup } } — the PRD's "Composition over
// admission" metric (#315, D9), defined once. composed = saved groups; placed = copies across every frame; admitted =
// RATIFIED proposals, split by entrance. A promoted group that is ratified counts in composed AND admitted.fromGroup.
export function compositionCount(doc) {
  const ratified = (Array.isArray(doc?.proposals) ? doc.proposals : []).filter((p) => p && p.status === "ratified");
  const fromImport = ratified.filter((p) => typeof p.recordId === "string").length;
  const fromGroup = ratified.filter((p) => typeof p.groupId === "string").length;
  return {
    composed: doc?.groups && typeof doc.groups === "object" ? Object.keys(doc.groups).length : 0,
    placed: groupInstances(doc).length,
    admitted: { total: fromImport + fromGroup, fromImport, fromGroup },
  };
}

// partProvenance(doc) → [{ frameId, partId, name, provenance, via }] — the PRD's "Supply" metric per part (#316), derived,
// never stored, total over junk. Every place a part enters a frame: a base frame's composition, a state's
// overrides.add, a lane's add, and each placed copy's definition parts (their `via` carries the groupId). A `group`
// node is `composed`; a node named a RATIFIED proposal's component is `imported` (from a record) or `admitted` (from
// a group); anything else is `vocabulary`. A copy's parts are named `<instanceId>/<partId>`, frameTree's naming. Here rather than in system/canvas-ops.mjs because this file is its only
// reader (compositionCount's precedent), which keeps it out of the runtime lines approach.html renders. "Hand-written"
// is NOT derivable: component.propose takes exactly one of recordId and groupId, so no proposal records a hand.
export function partProvenance(doc) {
  const obj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
  const ratified = new Map((Array.isArray(doc?.proposals) ? doc.proposals : [])
    .filter((p) => obj(p) && p.status === "ratified" && typeof p.component === "string").map((p) => [p.component, p]));
  const groups = obj(doc?.groups) ? doc.groups : {};
  const out = [];
  const walk = (node, frameId, via, pre = "") => {
    if (Array.isArray(node)) { node.forEach((n) => walk(n, frameId, via, pre)); return; }
    if (!obj(node)) return;
    if (obj(node.part)) { walk(node.part, frameId, via, pre); return; } // an add entry's {parentId, index, part} wrapper
    if (typeof node.id === "string") {
      const pr = ratified.get(node.name);
      const [provenance, own] = node.name === "group" ? ["composed", { groupId: node.props?.groupId ?? null, instanceId: node.id }]
        : !pr ? ["vocabulary", null]
        : typeof pr.recordId === "string" ? ["imported", { proposalId: pr.id, recordId: pr.recordId }]
        : ["admitted", { proposalId: pr.id, groupId: pr.groupId ?? null }];
      out.push({ frameId, partId: `${pre}${node.id}`, name: node.name ?? null, provenance, via: own || via ? { ...via, ...own } : null });
    }
    if (node.name === "group" && obj(groups[node.props?.groupId])) walk(groups[node.props.groupId].parts, frameId, { groupId: node.props.groupId }, `${pre}${node.id}/`);
    if (Array.isArray(node.children)) walk(node.children, frameId, via, pre);
  };
  for (const f of Array.isArray(doc?.frames) ? doc.frames : []) {
    if (!obj(f)) continue;
    walk(f.composition, f.id, null);
    if (obj(f.overrides)) walk(f.overrides.add, f.id, null);
  }
  for (const v of Array.isArray(doc?.variants) ? doc.variants : []) {
    for (const [fid, ov] of Object.entries(obj(v?.overrides) ? v.overrides : {})) if (obj(ov)) walk(ov.add, fid, { lane: v.key });
  }
  return out;
}

const PROVENANCES = Object.freeze(["imported", "admitted", "composed", "vocabulary"]);
const byProvenance = (rows) => Object.fromEntries(PROVENANCES.map((k) => [k, rows.filter((r) => r.provenance === k).length]));

function renderFlow(slug, doc, decs) {
  const out = [`# Flow — ${slug}`, "", `${provenance("`build/ops.jsonl`")} Lane A is the document; every other lane is its differences on A (G33).`];
  const c = compositionCount(doc);
  out.push("", "## Composition over admission", "",
    `- Composed and named: ${c.composed} group(s), ${c.placed} placed ${c.placed === 1 ? "copy" : "copies"}.`,
    `- Admitted through the chain: ${c.admitted.total} (${c.admitted.fromImport} from imports, ${c.admitted.fromGroup} from promoted groups).`,
    "", "A promoted group that is ratified counts in both lines (PRD § Success metrics, \"Composition over admission\" — reported, no target).");
  const pp = byProvenance(partProvenance(doc));
  out.push(`- Parts by provenance: ${PROVENANCES.map((k) => `${pp[k]} ${k}`).join(" · ")}.`);
  out.push("", "## Decisions changed since linked", "");
  const stale = staleFrames(doc, decs);
  if (decs === null) out.push("- Not checked — this package has no transcript.jsonl (a stand-in).");
  else if (!stale.length) out.push("- None — every linked decision is the latest on its question.");
  for (const x of stale) {
    const who = `- ${one(frameLabel(doc, x.frameId))} (${one(x.frameId)}): decision ${one(x.ref)}`;
    out.push(x.status === "stale" ? `${who} changed since linked — now ${one(x.latest)}. Re-confirm or re-link.` : `${who} does not resolve in the transcript (flagged, kept).`);
  }
  for (const key of laneKeys(doc)) {
    out.push("", key === null ? "## Lane A (base)" : `## Lane ${key}`, "");
    if (key !== null) out.push("Differences from lane A:", "", ...differences(doc, key), "");
    out.push("```mermaid", stateDiagram(doc, key), "```", "");
    const edges = flowEdges(doc, key);
    if (!edges.length) out.push("- No arrows in this lane.");
    for (const e of edges) out.push(`- From ${one(e.fromLabel)} (${one(e.from)}), ${one(edgePhrase(e))} goes to ${one(e.toLabel)} (${one(e.to)})${e.trigger ? `, when ${one(e.trigger)}` : ""}.`);
    out.push("", `Missing states (the floor is ${STATE_KEYS.join(" · ")}, plus any state a screen declares):`, "");
    const miss = missingStates(doc, key);
    if (!miss.length) out.push("- None — every screen in this lane has every state it requires.");
    for (const m of miss) out.push(`- ${one(frameLabel(doc, m.frameId))} (${one(m.frameId)}): ${m.missing.join(", ")}`);
    const flags = laneDoc(doc, key).doc.frames.flatMap((f) => frameTree(doc, f.id, key).flags
      .filter((fl) => ["dangling-set", "dangling-hide", "unsupported-add"].includes(fl.kind))
      .map((fl) => `- ${one(f.id)} · ${fl.kind}${fl.partId ? ` ${one(fl.partId)}` : ""}`));
    if (flags.length) out.push("", "Flagged (shown, never dropped):", "", ...flags);
  }
  return out.join("\n") + "\n";
}

// ---- drops.md ----------------------------------------------------------------------------------------

function renderDrops(slug, imports) {
  const out = [`# Drops — ${slug}`, "", provenance("`build/imports/*.json`")];
  if (!imports.length) {
    out.push("", "No imports — this build package has no import records, so nothing was dropped.");
    return out.join("\n") + "\n";
  }
  for (const i of imports) {
    out.push("", `## Import ${i.id}`);
    if (i.md === null) out.push("", "The record's markdown projection is missing — it is not in this pack.");
    const rows = Array.isArray(i.record?.drops) ? i.record.drops : [];
    for (const cls of DROP_CLASSES) {
      out.push("", `### ${cls}`, "");
      const mine = rows.filter((r) => r?.class === cls);
      if (!mine.length) out.push("- none");
      for (const r of mine) out.push(`- ${one(r.path ?? r.role ?? "?")} · ${one(r.kind ?? "owner")} — ${one(r.reason ?? r.why ?? "no reason recorded")}`);
    }
  }
  return out.join("\n") + "\n";
}

// ---- refusals.md -------------------------------------------------------------------------------------

function renderRefusals(slug, pkg) {
  const reasons = new Map(pkg.buildTranscript.filter((l) => l?.type === "refused" && Number.isInteger(l.seq)).map((l) => [l.seq, l]));
  // #320: a fork's unpicked option reads "refused: not-picked" — derived from its sibling's verdict, never stored.
  const np = new Set(notPickedOf(pkg.ops));
  const ledger = pkg.ops.filter((l) => l?.status === "refused").map((l) => {
    if (l.source === "owner") return `- seq ${l.seq} · owner refused the proposal at seq ${l.fromStep} (${l.op})${np.has(l.seq) ? " — refused: not-picked" : ""}`;
    const r = reasons.get(l.seq);
    return `- seq ${l.seq} · agent · ${l.op} — ${r ? `${one(r.kind)}: ${one(r.error ?? r.text)}` : "reason not recorded"}`;
  });
  const before = pkg.buildTranscript.filter((l) => l?.type === "refused" && !Number.isInteger(l.seq))
    .map((l) => `- turn ${one(l.turn)} · ${one(l.kind)} — ${one(l.error ?? l.text ?? "no reason recorded")}`);
  const imports = pkg.imports.flatMap((i) => i.transcript.filter((l) => l?.type === "denied")
    .map((l) => `- ${i.id} · ${one(l.tool)} denied via ${one(l.via)} — ${one(l.error)}`));
  const section = (title, rows) => ["", `## ${title}`, "", ...(rows.length ? rows : ["- none"])];
  return [`# Refusals — ${slug}`, "", provenance("`build/ops.jsonl`, `build/transcript.jsonl` and `build/imports/*.transcript.jsonl`"),
    ...section("On the ledger", ledger), ...section("Before the ledger", before), ...section("Imports", imports)].join("\n") + "\n";
}

// ---- lineage.json ------------------------------------------------------------------------------------

export const LINEAGE_DESCRIPTION = "Frame → decision → answer → evidence, by id: a decision is a record_decision line in the package's transcript.jsonl (its seq), an answer is an answers.jsonl ref, evidence is a file_evidence line (its seq). A broken link is a flag on its row, never a missing row. A state frame with no decision of its own is `via` its base. `seq` is the decision's transcript seq; `stale` is true once a later banked decision on the same question supersedes it (D2, #318), and `latest` names the head of that chain; a frame is stale when one of its decisions is, or via its base. Each frame's `parts` are partProvenance's rows (#316): imported, admitted, composed or vocabulary; `partsByProvenance` counts them. Generated by agent-layer/gen-build-handoff.mjs (#314) — do not edit.";

function renderLineage(doc, pkg) {
  const t = pkg.transcript;
  const opLines = (t ?? []).filter((l) => l?.type === "op");
  const bySeq = new Map(opLines.map((l) => [l.seq, l]));
  const stale = t === null ? [] : staleFrames(doc, opLines).filter((x) => x.status === "stale");
  const staleIds = new Set(stale.map((x) => x.frameId));
  const answers = new Set((pkg.answers ?? []).map((a) => a?.ref));
  const parts = partProvenance(doc);
  const frames = doc.frames.filter((f) => f && typeof f.id === "string").map((f) => {
    const refs = Array.isArray(f.decisionRefs) ? f.decisionRefs : [];
    const isState = f.baseId != null;
    const via = isState && !refs.length ? f.baseId : null;
    return { frameId: f.id, label: frameLabel(doc, f.id), baseId: f.baseId ?? null, decisionRefs: [...refs],
      via, stale: staleIds.has(f.id) || (via !== null && staleIds.has(via)), flags: !isState && !refs.length ? ["no-decision"] : [],
      parts: parts.filter((r) => r.frameId === f.id).map(({ frameId, ...r }) => r) };
  });
  const ids = [];
  for (const f of frames) for (const r of f.decisionRefs) if (!ids.includes(r)) ids.push(r);
  const decisions = ids.map((id) => {
    const flags = [];
    const seq = /^[1-9][0-9]*$/.test(id) ? Number(id) : null;
    const latest = stale.find((x) => x.ref === id)?.latest ?? null;
    const v = { id, seq, stale: latest !== null, latest };
    if (t === null) return { ...v, questionId: null, answerRef: null, answer: null, evidence: [], flags: ["no-transcript"] };
    const d = bySeq.get(Number(id));
    if (!d || d.op !== "record_decision") return { ...v, questionId: null, answerRef: null, answer: null, evidence: [], flags: ["unresolved-decision"] };
    const answerRef = d.params?.answer_ref ?? null;
    if (!answers.has(answerRef)) flags.push("unresolved-answer");
    const refs = Array.isArray(d.params?.evidence_refs) ? d.params.evidence_refs : [];
    if (!refs.length) flags.push("no-evidence");
    const evidence = refs.map((seq) => {
      const e = bySeq.get(seq);
      if (!e || e.op !== "file_evidence") { flags.push(`unresolved-evidence:${seq}`); return { seq, name: null, provenance: null }; }
      return { seq, name: e.params?.name ?? null, provenance: e.params?.provenance ?? null };
    });
    return { ...v, questionId: d.params?.question_id ?? null, answerRef, answer: answers.has(answerRef) ? "resolved" : null, evidence, flags };
  });
  const embodies = frames.flatMap((f) => f.decisionRefs.map((decisionId) => ({ frameId: f.frameId, decisionId })));
  return JSON.stringify({ $description: LINEAGE_DESCRIPTION, transcript: t === null ? "absent" : "present", frames, decisions, embodies, partsByProvenance: byProvenance(parts) }, null, 2) + "\n";
}

