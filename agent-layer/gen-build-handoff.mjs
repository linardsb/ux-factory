// gen-build-handoff.mjs — a build package → its handoff pack (epic #295 ticket #314;
// docs/epics/canvas-design-import.architecture.md § Data model, "The handoff pack, extended").
// Emits <pkg>/build/handoff/: flow.md (the state diagram as Mermaid stateDiagram-v2 per lane, G5's
// "tapping Continue goes to …" sentences, missing states per lane), drops.md (every import record's drop
// list in the three classes), refusals.md (the ledger's refused lines, the transcript-only refusals and
// the imports' denied lines), lineage.json (frame → decision → answer → evidence, by id) and
// imports/<id>.md (each record's own projection, verbatim).
//
// BESIDE THE PACKAGE, NEVER UNDER handoff/verdant/. A real package lives in the jobs folder and is never
// committed; its pack travels with it. handoff/verdant/ is the component pack, and gen-pack-index.mjs
// throws on a file there it has no route for.
//
// TWO HALVES: a PURE core (renderPack — no filesystem, no clock; same package in, same bytes out) and a
// THIN shell (readBuildPackage, writeBuildHandoff, genBuildHandoff, the CLI). Every lane read is
// system/canvas-ops.mjs's, so the canvas page, build-checks and this file answer from one code path (G33).
// The fold is canvas-store's foldLedger, so undo and refused lines mean what they mean on the page.
//
// FLAGGED, NEVER DROPPED: an unresolvable decision, answer or evidence ref keeps its row and carries a flag.
// An empty drops.md says "No imports" rather than being left out.
//
// CANNOT REACH: whether Mermaid parses flow.md (a human paste into mermaid.live), whether a drop's reason is
// true (group 42's), whether the page's Write button writes (canvas-journey pass L), whether a decision is a
// good one (a human read), and whether a jobs-folder package's pack is current (the drift leg sees committed
// packages only; the portal regenerates after every write route).
//
// Standalone:  node agent-layer/gen-build-handoff.mjs [--check]
//              node agent-layer/gen-build-handoff.mjs --root <pkgRoot>
// Paths resolve from this module (NOT cwd).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { foldLedger, listBuilds, loadBuild } from "../portal/lib/canvas-store.mjs";
import { STATE_KEYS, edgePhrase, flowEdges, frameLabel, frameTree, laneDoc, laneKeys, missingStates, stateDiagram } from "../system/canvas-ops.mjs";
import { DROP_CLASSES } from "../import/ir.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const PACK_DIR = "handoff";
export const PACK_FILES = Object.freeze(["flow.md", "drops.md", "refusals.md", "lineage.json"]);
export const PACKAGE_ROOTS = Object.freeze([join(ROOT, "discovery"), join(ROOT, "tooling/fixtures/builds")]);

const one = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const provenance = (what) => `Generated by \`agent-layer/gen-build-handoff.mjs\` from ${what} (#314). Regenerated, never hand-edited: a hand edit is lost.`;

// ---- flow.md -----------------------------------------------------------------------------------------

function differences(doc, key) {
  const v = (doc.variants ?? []).find((x) => x && x.key === key);
  const out = [];
  for (const [fid, ov] of Object.entries(v?.overrides ?? {})) {
    if (ov?.omit === true) { out.push(`- ${fid} · left out of this lane`); continue; }
    for (const [part, props] of Object.entries(ov?.set ?? {})) {
      for (const [prop, value] of Object.entries(props ?? {})) out.push(`- ${fid} · set ${part}.${prop} → ${JSON.stringify(value)}`);
    }
    for (const part of Array.isArray(ov?.hide) ? ov.hide : []) out.push(`- ${fid} · hide ${part}`);
    if (ov?.add !== undefined) out.push(`- ${fid} · add (not rendered; flagged)`);
  }
  return out.length ? out : ["- none"];
}

function renderFlow(slug, doc) {
  const out = [`# Flow — ${slug}`, "", `${provenance("`build/ops.jsonl`")} Lane A is the document; every other lane is its differences on A (G33).`];
  for (const key of laneKeys(doc)) {
    out.push("", key === null ? "## Lane A (base)" : `## Lane ${key}`, "");
    if (key !== null) out.push("Differences from lane A:", "", ...differences(doc, key), "");
    out.push("```mermaid", stateDiagram(doc, key), "```", "");
    const edges = flowEdges(doc, key);
    if (!edges.length) out.push("- No arrows in this lane.");
    for (const e of edges) out.push(`- From ${e.fromLabel} (${e.from}), ${edgePhrase(e)} goes to ${e.toLabel} (${e.to})${e.trigger ? `, when ${one(e.trigger)}` : ""}.`);
    out.push("", `Missing states (the floor is ${STATE_KEYS.join(" · ")}):`, "");
    const miss = missingStates(doc, key);
    if (!miss.length) out.push("- None — every screen in this lane meets the floor.");
    for (const m of miss) out.push(`- ${frameLabel(doc, m.frameId)} (${m.frameId}): ${m.missing.join(", ")}`);
    const flags = laneDoc(doc, key).doc.frames.flatMap((f) => frameTree(doc, f.id, key).flags
      .filter((fl) => ["dangling-set", "dangling-hide", "unsupported-add"].includes(fl.kind))
      .map((fl) => `- ${f.id} · ${fl.kind}${fl.partId ? ` ${fl.partId}` : ""}`));
    if (flags.length) out.push("", "Flagged (shown, never dropped):", "", ...flags);
  }
  return out.join("\n") + "\n";
}

// ---- drops.md ----------------------------------------------------------------------------------------

function renderDrops(slug, imports) {
  const out = [`# Drops — ${slug}`, "", provenance("`build/imports/*.json`")];
  if (!imports.length) {
    out.push("", "No imports — this build package has no import records, so nothing was dropped.");
    return out.join("\n") + "\n";
  }
  for (const i of imports) {
    out.push("", `## Import ${i.id}`);
    if (i.md === null) out.push("", "The record's markdown projection is missing — it is not in this pack.");
    const rows = Array.isArray(i.record?.drops) ? i.record.drops : [];
    for (const cls of DROP_CLASSES) {
      out.push("", `### ${cls}`, "");
      const mine = rows.filter((r) => r?.class === cls);
      if (!mine.length) out.push("- none");
      for (const r of mine) out.push(`- ${one(r.path ?? r.role ?? "?")} · ${one(r.kind ?? "owner")} — ${one(r.reason ?? r.why ?? "no reason recorded")}`);
    }
  }
  return out.join("\n") + "\n";
}

// ---- refusals.md -------------------------------------------------------------------------------------

function renderRefusals(slug, pkg) {
  const reasons = new Map(pkg.buildTranscript.filter((l) => l?.type === "refused" && Number.isInteger(l.seq)).map((l) => [l.seq, l]));
  const ledger = pkg.ops.filter((l) => l?.status === "refused").map((l) => {
    if (l.source === "owner") return `- seq ${l.seq} · owner refused the proposal at seq ${l.fromStep} (${l.op})`;
    const r = reasons.get(l.seq);
    return `- seq ${l.seq} · agent · ${l.op} — ${r ? `${one(r.kind)}: ${one(r.error ?? r.text)}` : "reason not recorded"}`;
  });
  const before = pkg.buildTranscript.filter((l) => l?.type === "refused" && !Number.isInteger(l.seq))
    .map((l) => `- turn ${one(l.turn)} · ${one(l.kind)} — ${one(l.error ?? l.text ?? "no reason recorded")}`);
  const imports = pkg.imports.flatMap((i) => i.transcript.filter((l) => l?.type === "denied")
    .map((l) => `- ${i.id} · ${one(l.tool)} denied via ${one(l.via)} — ${one(l.error)}`));
  const section = (title, rows) => ["", `## ${title}`, "", ...(rows.length ? rows : ["- none"])];
  return [`# Refusals — ${slug}`, "", provenance("`build/ops.jsonl`, `build/transcript.jsonl` and `build/imports/*.transcript.jsonl`"),
    ...section("On the ledger", ledger), ...section("Before the ledger", before), ...section("Imports", imports)].join("\n") + "\n";
}

// ---- lineage.json ------------------------------------------------------------------------------------

export const LINEAGE_DESCRIPTION = "Frame → decision → answer → evidence, by id: a decision is a record_decision line in the package's transcript.jsonl (its seq), an answer is an answers.jsonl ref, evidence is a file_evidence line (its seq). A broken link is a flag on its row, never a missing row. A state frame with no decision of its own is `via` its base. Generated by agent-layer/gen-build-handoff.mjs (#314) — do not edit.";

function renderLineage(doc, pkg) {
  const t = pkg.transcript;
  const bySeq = new Map((t ?? []).filter((l) => l?.type === "op").map((l) => [l.seq, l]));
  const answers = new Set((pkg.answers ?? []).map((a) => a?.ref));
  const frames = doc.frames.filter((f) => f && typeof f.id === "string").map((f) => {
    const refs = Array.isArray(f.decisionRefs) ? f.decisionRefs : [];
    const isState = f.baseId != null;
    return { frameId: f.id, label: frameLabel(doc, f.id), baseId: f.baseId ?? null, decisionRefs: [...refs],
      via: isState && !refs.length ? f.baseId : null, flags: !isState && !refs.length ? ["no-decision"] : [] };
  });
  const ids = [];
  for (const f of frames) for (const r of f.decisionRefs) if (!ids.includes(r)) ids.push(r);
  const decisions = ids.map((id) => {
    const flags = [];
    if (t === null) return { id, questionId: null, answerRef: null, answer: null, evidence: [], flags: ["no-transcript"] };
    const d = bySeq.get(Number(id));
    if (!d || d.op !== "record_decision") return { id, questionId: null, answerRef: null, answer: null, evidence: [], flags: ["unresolved-decision"] };
    const answerRef = d.params?.answer_ref ?? null;
    if (!answers.has(answerRef)) flags.push("unresolved-answer");
    const refs = Array.isArray(d.params?.evidence_refs) ? d.params.evidence_refs : [];
    if (!refs.length) flags.push("no-evidence");
    const evidence = refs.map((seq) => {
      const e = bySeq.get(seq);
      if (!e || e.op !== "file_evidence") { flags.push(`unresolved-evidence:${seq}`); return { seq, name: null, provenance: null }; }
      return { seq, name: e.params?.name ?? null, provenance: e.params?.provenance ?? null };
    });
    return { id, questionId: d.params?.question_id ?? null, answerRef, answer: answers.has(answerRef) ? "resolved" : null, evidence, flags };
  });
  const embodies = frames.flatMap((f) => f.decisionRefs.map((decisionId) => ({ frameId: f.frameId, decisionId })));
  return JSON.stringify({ $description: LINEAGE_DESCRIPTION, transcript: t === null ? "absent" : "present", frames, decisions, embodies }, null, 2) + "\n";
}

// ---- the pure core -----------------------------------------------------------------------------------

// renderPack(pkg) → { "flow.md": text, …, "imports/<id>.md": text } — PURE. `pkg` is readBuildPackage's shape.
export function renderPack(pkg) {
  const doc = foldLedger(pkg.ops).doc;
  const out = {
    "flow.md": renderFlow(pkg.slug, doc),
    "drops.md": renderDrops(pkg.slug, pkg.imports),
    "refusals.md": renderRefusals(pkg.slug, pkg),
    "lineage.json": renderLineage(doc, pkg),
  };
  for (const i of pkg.imports) if (i.md !== null) out[`imports/${i.id}.md`] = i.md;
  return out;
}

// ---- the thin shell ----------------------------------------------------------------------------------

const readJsonl = (file) => readFileSync(file, "utf8").split("\n").flatMap((text, i) => {
  if (!text.trim()) return [];
  try { return [JSON.parse(text)]; }
  catch (e) { throw new Error(`${file} line ${i + 1} is not JSON — ${e.message}`); }
});
const maybe = (file) => (existsSync(file) ? readJsonl(file) : null);

// readBuildPackage(pkgRoot) → { slug, ops, transcript, answers, buildTranscript, imports } — or null when the
// package has no build half.
export function readBuildPackage(pkgRoot) {
  const pkg = loadBuild(join(pkgRoot, "build"));
  if (!pkg) return null;
  const dir = join(pkgRoot, "build", "imports");
  const ids = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort() : [];
  return {
    slug: pkgRoot.split(/[\\/]/).filter(Boolean).pop(),
    ops: pkg.ops,
    transcript: maybe(join(pkgRoot, "transcript.jsonl")),
    answers: maybe(join(pkgRoot, "answers.jsonl")),
    buildTranscript: maybe(join(pkgRoot, "build", "transcript.jsonl")) ?? [],
    imports: ids.map((id) => ({
      id,
      record: JSON.parse(readFileSync(join(dir, `${id}.json`), "utf8")),
      md: existsSync(join(dir, `${id}.md`)) ? readFileSync(join(dir, `${id}.md`), "utf8") : null,
      transcript: maybe(join(dir, `${id}.transcript.jsonl`)) ?? [],
    })),
  };
}

const walk = (dir) => (existsSync(dir) ? readdirSync(dir).sort().flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
}) : []);

// writeBuildHandoff(pkgRoot) → { dir, files } — the whole pack, rewritten. The imports/ subdir is rebuilt from
// scratch (#64's rule: a removed record leaves no orphaned md). A package with no build half writes nothing.
export function writeBuildHandoff(pkgRoot) {
  const pkg = readBuildPackage(pkgRoot);
  const dir = join(pkgRoot, "build", PACK_DIR);
  if (!pkg) return { dir, files: [] };
  rmSync(join(dir, "imports"), { recursive: true, force: true });
  const files = [];
  for (const [rel, text] of Object.entries(renderPack(pkg))) {
    const p = join(dir, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
    files.push(p);
  }
  return { dir, files };
}

// committedPackages() → absolute package roots: every discovery/<slug> and tooling/fixtures/builds/<slug> with a build/.
export const committedPackages = () => PACKAGE_ROOTS.flatMap((dir) =>
  listBuilds([{ provenance: "fictional", dir }]).map((b) => join(dir, b.slug)));

// genBuildHandoff({ check }) → { packages, files, drifted } — check mode compares every rendered file to disk (a
// missing file is drift) and reports every file on disk the render did not produce (an orphan is drift too).
export function genBuildHandoff({ check = false } = {}) {
  const drifted = [];
  let files = 0;
  const roots = committedPackages();
  for (const p of roots) {
    const rendered = renderPack(readBuildPackage(p));
    files += Object.keys(rendered).length;
    if (!check) { writeBuildHandoff(p); continue; }
    const dir = join(p, "build", PACK_DIR);
    for (const [rel, text] of Object.entries(rendered)) {
      let prior;
      try { prior = readFileSync(join(dir, rel), "utf8"); } catch { prior = null; }
      if (prior !== text) drifted.push(relative(ROOT, join(dir, rel)));
    }
    for (const f of walk(dir)) if (!Object.hasOwn(rendered, relative(dir, f).split("\\").join("/"))) drifted.push(`${relative(ROOT, f)} (orphan)`);
  }
  return { packages: roots.length, files, drifted };
}

// pathToFileURL, not `file://${argv[1]}`: this repo's path contains a space.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const at = process.argv.indexOf("--root");
    if (at !== -1) {
      const r = writeBuildHandoff(resolve(process.argv[at + 1] ?? ""));
      console.log(`build handoff  ✓  ${r.files.length} files (${r.dir})`);
    } else {
      const check = process.argv.includes("--check");
      const r = genBuildHandoff({ check });
      if (check && r.drifted.length) {
        console.error(`build handoff ✗  drift: ${r.drifted.join(", ")} — regenerate with: node agent-layer/gen-build-handoff.mjs`);
        process.exit(1);
      }
      console.log(`build handoff  ✓  ${r.packages} packages, ${r.files} files${check ? " — no drift" : ""}`);
    }
  } catch (e) {
    console.error(`build handoff ✗  ${e.message}`);
    process.exit(1);
  }
}
